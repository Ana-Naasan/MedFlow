// One-off generator: builds lib/mock-data/whitmore-records.ts from the
// real PDF files served under public/records/whitmore.
// Run: node scripts/gen-whitmore-records.mjs
import fs from "node:fs"
import path from "node:path"
import { fileURLToPath } from "node:url"

const __dirname = path.dirname(fileURLToPath(import.meta.url))
const ROOT = path.resolve(__dirname, "..")
const PDF_DIR = path.join(ROOT, "public", "records", "whitmore")
const OUT = path.join(ROOT, "lib", "mock-data", "whitmore-records.ts")

const PATIENT_ID = "99021"

// Heuristic: pick an encounter type from the slug.
function encounterType(slug) {
  if (/(arthroplasty|biopsy|angiography|phacoemulsification|stent|pci|polypectomy|imrt|pet|mri|dexa|radiograph|ultrasound|echocardiog|endoscopy|colonoscopy|egd)/.test(slug)) {
    return "specialist"
  }
  if (/(decompensated|exacerbation|pneumonia|acute|fall|fracture|tia|hypoxemic)/.test(slug)) {
    return "emergency"
  }
  return "office-visit"
}

function titleFromSlug(slug) {
  const words = slug.replace(/-/g, " ").trim()
  return words.charAt(0).toUpperCase() + words.slice(1)
}

const files = fs
  .readdirSync(PDF_DIR)
  .filter((f) => /^\d{2}_/.test(f) && f.toLowerCase().endsWith(".pdf"))
  .sort()

const fileRecords = []
const encounters = []

for (const fname of files) {
  const m = fname.match(/^(\d{2})_(\d{4}-\d{2}-\d{2})_(.+)\.pdf$/i)
  if (!m) continue
  const [, num, date, slug] = m
  const isIndex = /index/i.test(slug)
  const title = isIndex ? "Medical Record Index" : titleFromSlug(slug)
  const sizeKb = Math.max(1, Math.round(fs.statSync(path.join(PDF_DIR, fname)).size / 1024))
  const url = `/records/whitmore/${encodeURIComponent(fname)}`
  const fileId = `file-hwpdf-${num}`

  fileRecords.push({
    id: fileId,
    patientId: PATIENT_ID,
    name: fname,
    type: "pdf",
    uploadedAt: `${date}T09:00:00`,
    uploadedBy: "Riverside Family Health Clinic",
    sizeKb,
    url,
  })

  if (isIndex) continue

  encounters.push({
    id: `enc-hwpdf-${num}`,
    patientId: PATIENT_ID,
    date,
    type: encounterType(slug.toLowerCase()),
    physician: "Park, Eleanor",
    chiefComplaint: title,
    summary: `${title}. Open the attached document for the full clinical record.`,
    attachedDocuments: [fileId],
  })
}

const header = `// AUTO-GENERATED by scripts/gen-whitmore-records.mjs — do not edit by hand.
// Sources the real Whitmore medical-record PDFs served from public/records/whitmore.
import type { Encounter, FileRecord } from "@/lib/types";

`

const body =
  `export const whitmoreFiles: FileRecord[] = ${JSON.stringify(fileRecords, null, 2)};\n\n` +
  `export const whitmoreEncounters: Encounter[] = ${JSON.stringify(encounters, null, 2)};\n`

fs.writeFileSync(OUT, header + body)
console.log(`Wrote ${OUT}`)
console.log(`  files: ${fileRecords.length}, encounters: ${encounters.length}`)
